#!/usr/bin/env node
// Regenerates engine/catalog-unmodeled.js: reference-added WRITE / PERMISSIONS actions that
// no detector models. Usage: node scripts/gen-unmodeled-escalation.mjs [--baseline <rev>] [--check]
//
// Candidate = the engine answered "unknown" (exit 3) with the baseline snapshot (the rev
// before the full-service refresh, default 62e505a) but exit 0 with the current snapshot on a
// narrow-ARN single-action Allow, and the reference level is WRITE or PERMISSIONS. A candidate
// is dropped when a named detector already fires: alone, or paired with iam:PassRole on a role.
// READ/LIST/TAGGING stay known (no detector treats them as escalation, and withholding
// ec2:Describe* members would fail every read-only policy closed).
import { execFileSync } from 'node:child_process';
import { cpSync, mkdtempSync, readFileSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const engine = 'content/tools/iam-blast-radius/engine';
const args = process.argv.slice(2);
const argVal = (k, d) => (args.includes(k) ? args[args.indexOf(k) + 1] : d);
const baselineRev = argVal('--baseline', '62e505a');
const OUT = join(root, engine, 'catalog-unmodeled.js');
const EMPTY = "export const UNMODELED_ESCALATION = Object.freeze([]);\n";

const tmp = mkdtempSync(join(tmpdir(), 'unmodeled-'));
function tree(name, refSource) {
  const dir = join(tmp, name);
  cpSync(join(root, 'cli'), join(dir, 'cli'), { recursive: true });
  cpSync(join(root, 'content'), join(dir, 'content'), { recursive: true });
  writeFileSync(join(dir, engine, 'catalog-unmodeled.js'), EMPTY);
  if (refSource) {
    cpSync(join(dir, engine, 'catalog-aws-ref.js'), join(dir, engine, 'catalog-aws-ref.cur.js'));
    writeFileSync(join(dir, engine, 'catalog-aws-ref.js'), refSource);
  }
  return dir;
}
const scanner = async (dir) => (await import(pathToFileURL(join(dir, 'cli/scan.mjs')))).scan;
const pol = (stmts) => JSON.stringify({ Version: '2012-10-17', Statement: stmts });
const run = (scan, stmts) => scan({ text: pol(stmts), family: 'identity', threshold: 'high',
  subjectAccount: '123456789012', partition: 'aws' });
const narrow = (svc) => `arn:aws:${svc}:us-east-2:123456789012:res/name`;

try {
  // Baseline engine: current engine code, snapshot restricted to the actions the baseline rev had.
  const baseFile = join(tmp, 'baseline-ref.mjs');
  writeFileSync(baseFile, execFileSync('git', ['-C', root, 'show', `${baselineRev}:${engine}/catalog-aws-ref.js`], { encoding: 'utf8' }));
  const baseRef = (await import(pathToFileURL(baseFile))).AWS_REF_ACTIONS;
  const curRef = (await import(pathToFileURL(join(root, engine, 'catalog-aws-ref.js')))).AWS_REF_ACTIONS;
  const filtered = {};
  for (const [s, acts] of Object.entries(baseRef)) filtered[s] = acts;
  const baseSrc = `import * as C from './catalog-aws-ref.cur.js';\n`
    + `export const AWS_REF_ACTIONS = Object.freeze(${JSON.stringify(filtered)});\n`
    + `export const AWS_REF_REQUIRES_WILDCARD = C.AWS_REF_REQUIRES_WILDCARD;\n`
    + `export const AWS_SERVICE_PREFIXES = C.AWS_SERVICE_PREFIXES;\n`;
  const scanBase = await scanner(tree('base', baseSrc));
  const scanCur = await scanner(tree('cur'));

  const kept = []; const covered = []; const stats = {};
  for (const [svc, acts] of Object.entries(curRef)) {
    for (const [name, level] of Object.entries(acts)) {
      if (level !== 'WRITE' && level !== 'PERMISSIONS') continue;
      const one = [{ Effect: 'Allow', Action: `${svc}:${name}`, Resource: narrow(svc) }];
      if (run(scanBase, one).exitCode !== 3) continue; // known before the refresh
      const alone = run(scanCur, one);
      if (alone.exitCode !== 0) continue; // already failed closed or flagged
      const paired = run(scanCur, [...one, { Effect: 'Allow', Action: 'iam:PassRole',
        Resource: 'arn:aws:iam::123456789012:role/admin' }]);
      const key = `${svc}:${name}`.toLowerCase();
      if ((paired.findings || []).some((f) => /^PASSROLE-/.test(f.id))) { covered.push(key); continue; }
      kept.push(key);
      stats[`${svc} ${level}`] = (stats[`${svc} ${level}`] || 0) + 1;
    }
  }
  kept.sort();
  const body = '// GENERATED by scripts/gen-unmodeled-escalation.mjs - do not edit by hand.\n'
    + `// Baseline snapshot: ${baselineRev}. ${kept.length} reference-added WRITE/PERMISSIONS actions that no\n`
    + '// detector models; catalog.js withholds them so an Allow of one stays an UNKNOWN_ACTION (exit 3).\n'
    + 'export const UNMODELED_ESCALATION = Object.freeze([\n'
    + kept.map((k) => `  '${k}',`).join('\n') + '\n]);\n';
  console.log(JSON.stringify({ baselineRev, withheld: kept.length, coveredByPassRole: covered, perServiceLevel: stats }, null, 1));
  if (args.includes('--check')) {
    if (readFileSync(OUT, 'utf8') !== body) { console.error('catalog-unmodeled.js is stale; rerun without --check'); process.exitCode = 1; }
  } else writeFileSync(OUT, body);
} finally {
  rmSync(tmp, { recursive: true, force: true });
}
